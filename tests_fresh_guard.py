"""fresh_guard: текст «сон ще не приходив» при свіжому сні — блок; чужі речі не чіпаємо."""
import sys
import fresh_guard as fg

FAILS = []
def ok(n, c):
    print(("ok   " if c else "FAIL ") + n)
    if not c: FAILS.append(n)

A = {"today": "2026-11-14",
     "sleep": {"last_day": "2026-11-14", "last": 10.5},
     "weight": {"last_day": "2026-11-11", "last": 84.7},
     "hr": {"last_day": "2026-11-14", "last": 45},
     "hrv": {"last_day": "2026-11-14", "last": 60},
     "steps": {"last_day": "2026-11-14", "last": 13000}}

t1 = "⚡ Сон за сьогодні ще не надходив, останнє відоме — 2026-11-13, 1 день тому; враховуючи твій графік."
ok("сон є, текст каже не надходив -> блок", "сон" in fg.contradiction(t1, A))
ok("вага справді стара -> не блок", fg.contradiction("Вага за сьогодні ще не приходила, останнє відоме — 2026-11-11.", A) == "")
ok("пульс/HRV свіжі, 'старі дані' -> блок", fg.contradiction("Пульс і HRV — старі дані, оновлюю.", A) != "")
ok("нормальний текст -> не блок", fg.contradiction("Сон 10.5 год, HRV 60 — відновлення добре.", A) == "")
ok("Сонце Квадрат (астро) не плутається зі сном", fg.contradiction("Сонце Квадрат Юпітер — дані ще не надходили", A) == "")
ok("лист 'не приходив' без показника -> не блок", fg.contradiction("Лист від банку ще не приходив.", A) == "")
ok("кроки свіжі + 'кроки не надходили' -> блок", fg.contradiction("Кроки не надходили сьогодні.", A) != "")

p = "Факти:\nСон: 10.5 год\nМинуле: Сон за сьогодні ще не надходив, останнє відоме — 2026-11-13\nВага: 84.7 [!!СТАРІ ДАНІ за 2026-11-11!!]\nЕнергія ще не приходила?"
s = fg.scrub_prompt(p)
ok("scrub прибрав спогад про сон", "ще не надходив" not in s)
ok("scrub лишив службову позначку СТАРІ ДАНІ", "СТАРІ ДАНІ" in s)
ok("scrub лишив факти", "Сон: 10.5" in s)
ok("scrub без збігів повертає той самий текст", fg.scrub_prompt("привіт") == "привіт")

A2 = dict(A)
A2["hrv"] = {"last_day": "2026-11-14", "last": 60.0, "avg7": 53.1}
A2["sleep"] = {"last_day": "2026-11-14", "last": 10.5, "avg7": 7.9}
ok("HRV 60 > 53.1, «впав» -> помилка напрямку", fg.direction_error("🚀 HRV впав до 60.0 мс (сер.7д 53.1 мс), що може вказувати на стрес.", A2) != "")
ok("HRV 60 > 53.1, «зріс» -> ок", fg.direction_error("HRV зріс до 60 мс (сер.7д 53.1).", A2) == "")
ok("сон 10.5 > 7.9 «значно більше за середні» -> ок", fg.direction_error("Сон 10.5 год, значно більше за середні 7.9.", A2) == "")
ok("сон «нижчий за норму» при 10.5 -> помилка", fg.direction_error("Сон нижчий за норму.", A2) != "")
ok("різниця <3% не чіпаємо", fg.direction_error("HRV впав до 53.5", {"today":"2026-11-14","hrv":{"last_day":"2026-11-14","last":53.5,"avg7":53.1}}) == "")
ok("any_error ловить напрямок", fg.any_error("HRV впав до 60", A2) != "")
# false-positive: тижневі/відсоткові тренди не блокуємо (15.11 заблоковано тижневий звіт)
_a = {"today": "2026-11-15", "hrv": {"last": 41, "avg7": 49.1, "last_day": "2026-11-15"},
      "energy": {"last": 60, "avg7": 40, "last_day": "2026-11-15"}}
ok("fp", fg.direction_error("Body Battery впав на 24% за тиждень.", _a) == "")
ok("fp", fg.direction_error("Минулого тижня Body Battery впав до 27.", _a) == "")
ok("fp", fg.direction_error("Body Battery впав до 25 (сер. 40).", _a) == "")
ok("fp", fg.direction_error("Body Battery впав до 60 (сер. 40).", _a) != "")

print("FAILS:", FAILS or "none")
sys.exit(1 if FAILS else 0)

