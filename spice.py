"""
spice.py — шаблонні нагадування мусять бути цікавими й ефективними.

Скарга Олега (22.08): «Текст сповіщення звітів нагадування якийсь простий.
Зроби його цікавим, ефективнішим».

variety.py уже зробив живими AI-тексти. Але картки нагадувань складаються
НЕ AI, а f-рядками в модулях — і там хвіст був статичний:
  dates_book:  «Є час підготуватись без спіху.»        (щоразу те саме)
  subs:        «Якщо не користуєшся — скасувати треба ДО списання.»
  bills:       взагалі без хвоста — сухий перелік полів
  deadlines:   те саме
Такий рядок не додає ні інформації, ні мотиву щось зробити.

ЩО РОБИТЬ ЦЕЙ МОДУЛЬ
Замість одного мертвого рядка дає хвіст із трьох частин:
  СТАВКА  — що конкретно на кону (сума, скільки днів, скільки на рік);
  КРОК    — одна конкретна дія зараз, а не «не забудь»;
  і все це в ротації, тому наступне нагадування звучить інакше.

Принципи (як і всюди в проєкті):
  • нічого не вигадуємо — беремо тільки передані факти; немає факту → рядок,
    що його не потребує;
  • без порожньої мотивації («тримай темп», «все під контролем»);
  • ротація детермінована (ключ + день), тому нагадування про ОДНУ подію на
    різних порогах 7/3/1/0 днів дає різні тексти, а не копію.

API:
    tail(kind, days_left=None, facts=None, key="")  -> str
    money_line(amount, cycle)                       -> str
    urgency(days_left)                              -> str
"""
