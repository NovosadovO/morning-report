# Тон під залишок часу — «через 7 днів» і «сьогодні» не можуть звучати однаково.
URGENCY = {
    0: "⚡ Сьогодні. Далі відкладати нема куди.",
    1: "🔥 Завтра. Останній спокійний вечір, щоб зробити.",
    3: "⏳ Лишилось {d} дн. — вже пора, а не «потім».",
    7: "🗓 Ще {d} дн. — можна зробити спокійно, без нервів.",
}


def _pick(seq, key, salt=""):
    """Детермінований вибір: різний для різних подій і різних днів,
    але стабільний у межах одного дня — щоб дубль не дав інший текст."""
    if not seq:
        return ""
    h = zlib.crc32((str(key) + "|" + str(salt) + "|"
                    + date.today().isoformat()).encode("utf-8", "ignore"))
    return seq[h % len(seq)]


def urgency(days_left):
    """Рядок терміновості з реальним числом днів."""
    try:
        d = int(days_left)
    except Exception:
        return ""
    for thr in (0, 1, 3, 7):
        if d <= thr:
            return URGENCY[thr].format(d=d)
    return "🗓 Ще " + str(d) + " дн. — у полі зору, не в роботі."


def money_line(amount, cycle="monthly"):
    """Скільки це насправді коштує на рік. Найсильніший аргумент по підписках."""
    try:
        a = float(amount)
    except Exception:
        return ""
    if a <= 0:
        return ""
    mult = {"monthly": 12.0, "yearly": 1.0, "quarterly": 4.0, "weekly": 52.0}
    per_year = a * mult.get(str(cycle), 12.0)
    if per_year >= 100:
        return ("Це " + str(int(round(per_year))) + "€ на рік — "
                + "вирішувати варто саме такими числами, а не місячними.")
    return "Це " + str(int(round(per_year))) + "€ на рік."


def tail(kind, days_left=None, facts=None, key=""):
    """Живий хвіст картки: ставка + один крок (+ терміновість, якщо є дні).

    kind: date | bill | deadline | sub
    facts: {"amount": 12.99, "cycle": "monthly"} — необов'язково; використаємо
           тільки те, що реально передали (нічого не вигадуємо).
    """
    k = str(kind or "").lower()
    if k not in STAKE:
        return ""
    facts = facts or {}
    kk = str(key or k)
    out = []
    u = urgency(days_left) if days_left is not None else ""
    if u:
        out.append(u)
    st = _pick(STAKE[k], kk, "stake" + str(days_left))
    if st:
        out.append(st)
    if k == "sub":
        ml = money_line(facts.get("amount"), facts.get("cycle", "monthly"))
        if ml:
            out.append(ml)
    sp = _pick(STEP[k], kk, "step" + str(days_left))
    if sp:
        out.append("➡️ " + sp)
    return "\n".join(out)


