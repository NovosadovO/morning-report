"""
Офлайн-тест: _kv_from_text() парсить розлогий AI-опис зі скріну QWatch Pro
(таке, як реально надсилає Олег), а не тільки короткий формат "вага 83 сон 7г".

Баг був у тому, що QWatch Pro у деяких випадках повертає готовий AI-АНАЛІЗ
("Вот анализ ваших данных здоровья..."), де число стоїть ПЕРЕД одиницею
("вес — 83 кг", "725 шагов", "68 ударов"), а не ПІСЛЯ ключового слова, як
очікував старий парсер ("вага 83", "кроки 725") — тож усе окрім пульсу
губилось або ловилось криво (сон = "2" замість 11:09 — бо регекс хапав
перше число з розбивки "глубокий сон — 2:51").
"""

import re

FAILS = []


def check(name, cond, extra=""):
    if cond:
        print(f"  ok   {name}")
    else:
        print(f"  FAIL {name} {extra}")
        FAILS.append(name)


import healthai as H  # noqa: E402

RAW_RU = (
    "Вот анализ ваших данных здоровья из предоставленного отчета:   "
    "Основные показатели  Показатель здоровья: 87%.    "
    "Дата и время: 2026-09-21 13:04.    "
    "Антропометрические данные: возраст — 37 лет, рост — 175 см, вес — 83 кг.   "
    "Анализ ключевых параметров  Общий вывод: вы демонстрируете хороший уровень "
    "физической активности, отличный сон и стабильное состояние здоровья по "
    "большинству параметров.    "
    "Кроки (Шаги): ваша активность сегодня составила 725 шагов, что является "
    "относительно низким показателем за день.    "
    "Сон: качество сна оценено на 100 баллов при общем времени 11:09 "
    "(глубокий сон — 2:51, легкий сон — 5:18), что способствует хорошему "
    "восстановлению организма.    "
    "Сердце: средний пульс составляет 68 ударов в минуту, что свидетельствует "
    "о нормальном и стабильном состоянии сердечно-сосудистой системы"
)

print("\n1. Розлогий AI-опис (RU) — усі поля витягнуто правильно")
kv = H._kv_from_text(RAW_RU)
check("вага 83", kv.get("weight") == "83", kv)
check("кроки 725", kv.get("steps") == "725", kv)
check("пульс 68", kv.get("hr") == "68", kv)
check("health_score 87", kv.get("health_score") == "87", kv)
check("сон = загальні 11:09 (669 хв), НЕ 2:51 з розбивки",
      kv.get("sleep_min") == 669, kv)

print("\n2. Через qwsync.normalize() дає коректний запис")
import qwsync  # noqa: E402
rec = qwsync.normalize(kv)
check("steps=725", rec.get("steps") == 725, rec)
check("hr_avg=68", rec.get("hr_avg") == 68, rec)
check("weight_kg=83.0", rec.get("weight_kg") == 83.0, rec)
check("health_score=87", rec.get("health_score") == 87, rec)
check("sleep_total_min=669", rec.get("sleep_total_min") == 669, rec)
check("sleep_hours=11.15", rec.get("sleep_hours") == 11.15, rec)

print("\n3. Без total time — сума глибокий+легкий як fallback")
raw_no_total = (
    "Сон: глубокий сон — 1:30, легкий сон — 4:00. "
    "Пульс: 60 ударов. Вес: 80 кг. 1000 шагов."
)
kv2 = H._kv_from_text(raw_no_total)
check("сон = 1:30 + 4:00 = 330 хв", kv2.get("sleep_min") == 330, kv2)

print("\n4. Короткий формат і досі працює (без регресії)")
kv3 = H._kv_from_text("вага 83,4 сон 7г 20хв кроки 9 120 пульс 68")
check("вага", kv3.get("weight") == "83,4", kv3)
check("сон у хвилинах", kv3.get("sleep_min") == 440, kv3)
check("кроки", kv3.get("steps") == "9120", kv3)
check("пульс", kv3.get("hr") == "68", kv3)

print("\n5. Українською теж")
raw_ua = "Показник здоров'я: 90%. Вага — 82 кг. Кроків: 5000. Пульс: 65 ударів."
kv4 = H._kv_from_text(raw_ua)
check("health_score ua", kv4.get("health_score") == "90", kv4)
check("вага ua", kv4.get("weight") == "82", kv4)
check("пульс ua", kv4.get("hr") == "65", kv4)

if FAILS:
    print(f"\n❌ FAILS: {FAILS}")
    raise SystemExit(1)
print("\nВСЕ ОК")
